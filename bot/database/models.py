"""
SQLAlchemy Async ORM models for TeleGroup Management Bot.
Supports PostgreSQL (asyncpg) and SQLite (aiosqlite).
"""

from datetime import datetime
from typing import Optional, List
from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    Enum as SQLEnum,
    UniqueConstraint
)
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()


class Group(Base):
    """Registered Telegram Group managed by the bot."""
    __tablename__ = "groups"

    id = Column(Integer, primary_key=True, autoincrement=True)
    tg_chat_id = Column(BigInteger, unique=True, nullable=False, index=True)
    title = Column(String(255), nullable=False)
    username = Column(String(255), nullable=True)
    is_active = Column(Boolean, default=True)

    # Moderation parameters
    warn_limit = Column(Integer, default=3)
    warn_action = Column(String(32), default="mute")  # mute, kick, ban
    mute_duration_minutes = Column(Integer, default=60)
    rules_text = Column(Text, default="No spamming, be respectful, and follow community standards.")

    # Anti-Spam & Safety parameters
    flood_limit = Column(Integer, default=5)  # max msgs in 5 sec
    repeat_limit = Column(Integer, default=3)  # max identical messages
    block_links = Column(Boolean, default=False)
    block_forwards = Column(Boolean, default=False)
    blocked_words = Column(Text, default="")  # comma-separated

    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    admins = relationship("GroupAdmin", back_populates="group", cascade="all, delete-orphan")
    link_codes = relationship("LinkCode", back_populates="group", cascade="all, delete-orphan")
    welcome_config = relationship("WelcomeConfig", back_populates="group", uselist=False, cascade="all, delete-orphan")
    goodbye_config = relationship("GoodbyeConfig", back_populates="group", uselist=False, cascade="all, delete-orphan")
    warnings = relationship("UserWarning", back_populates="group", cascade="all, delete-orphan")
    moderation_logs = relationship("ModerationLog", back_populates="group", cascade="all, delete-orphan")
    filter_rules = relationship("FilterRule", back_populates="group", cascade="all, delete-orphan")


class GroupAdmin(Base):
    """Verified group administrators authorized to control settings."""
    __tablename__ = "group_admins"

    id = Column(Integer, primary_key=True, autoincrement=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)
    tg_user_id = Column(BigInteger, nullable=False, index=True)
    role = Column(String(64), default="administrator")  # creator, administrator
    can_manage_settings = Column(Boolean, default=True)
    can_crosspost = Column(Boolean, default=True)
    can_moderate = Column(Boolean, default=True)
    verified_at = Column(DateTime, default=datetime.utcnow)

    group = relationship("Group", back_populates="admins")

    __table_args__ = (
        UniqueConstraint("group_id", "tg_user_id", name="uq_group_admin"),
    )


class LinkCode(Base):
    """Single-use temporary connection codes generated by /linkgroup."""
    __tablename__ = "link_codes"

    id = Column(Integer, primary_key=True, autoincrement=True)
    code = Column(String(16), unique=True, nullable=False, index=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)
    generated_by_user_id = Column(BigInteger, nullable=False)
    expires_at = Column(DateTime, nullable=False)
    is_used = Column(Boolean, default=False)
    used_at = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    group = relationship("Group", back_populates="link_codes")


class CrossPostConnection(Base):
    """Cross-posting pipeline connecting two Telegram groups."""
    __tablename__ = "crosspost_connections"

    id = Column(Integer, primary_key=True, autoincrement=True)
    name = Column(String(128), default="Cross-Posting Pipeline")
    group_a_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)
    group_b_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)

    # Direction: A_TO_B, B_TO_A, BIDIRECTIONAL
    direction = Column(String(32), default="A_TO_B", nullable=False)

    # Mode: COPY (clean clone without forward header), FORWARD (with original attribution)
    mode = Column(String(32), default="COPY", nullable=False)

    is_active = Column(Boolean, default=True)
    admin_only = Column(Boolean, default=False)
    allowed_types = Column(String(32), default="ALL")  # ALL, TEXT_ONLY, MEDIA_ONLY

    created_by_user_id = Column(BigInteger, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    group_a = relationship("Group", foreign_keys=[group_a_id])
    group_b = relationship("Group", foreign_keys=[group_b_id])


class CrossPostMessageMap(Base):
    """Message ID mapping for anti-loop protection and edit tracking."""
    __tablename__ = "crosspost_message_maps"

    id = Column(Integer, primary_key=True, autoincrement=True)
    connection_id = Column(Integer, ForeignKey("crosspost_connections.id", ondelete="CASCADE"), nullable=False)
    source_chat_id = Column(BigInteger, nullable=False, index=True)
    source_msg_id = Column(BigInteger, nullable=False, index=True)
    dest_chat_id = Column(BigInteger, nullable=False, index=True)
    dest_msg_id = Column(BigInteger, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    __table_args__ = (
        UniqueConstraint("source_chat_id", "source_msg_id", "dest_chat_id", name="uq_crosspost_msg"),
    )


class WelcomeConfig(Base):
    """Automated welcome message configuration for a group."""
    __tablename__ = "welcome_configs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), unique=True, nullable=False)
    is_enabled = Column(Boolean, default=True)
    template_text = Column(
        Text,
        default="👋 Welcome to {group_name}, {first_name}!\nPlease read our group rules and enjoy your stay."
    )
    media_url = Column(String(512), nullable=True)
    delete_after_seconds = Column(Integer, default=60)  # 10, 30, 60, 120, 300, 0 (disabled)
    buttons_json = Column(Text, default="[]")  # JSON list of [{"text": "Rules", "url": "..."}]

    group = relationship("Group", back_populates="welcome_config")


class GoodbyeConfig(Base):
    """Automated departure message configuration for a group."""
    __tablename__ = "goodbye_configs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), unique=True, nullable=False)
    is_enabled = Column(Boolean, default=False)
    template_text = Column(Text, default="👋 Goodbye, {first_name}!")
    delete_after_seconds = Column(Integer, default=60)

    group = relationship("Group", back_populates="goodbye_config")


class UserWarning(Base):
    """Warning record for moderation tracking."""
    __tablename__ = "user_warnings"

    id = Column(Integer, primary_key=True, autoincrement=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)
    tg_user_id = Column(BigInteger, nullable=False, index=True)
    warned_by_user_id = Column(BigInteger, nullable=False)
    reason = Column(String(255), default="Rule violation")
    created_at = Column(DateTime, default=datetime.utcnow)

    group = relationship("Group", back_populates="warnings")


class ModerationLog(Base):
    """Audit log for all moderation actions."""
    __tablename__ = "moderation_logs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)
    tg_user_id = Column(BigInteger, nullable=False)
    action = Column(String(32), nullable=False)  # WARN, MUTE, UNMUTE, KICK, BAN, UNBAN, PURGE
    reason = Column(String(255), nullable=True)
    executed_by_user_id = Column(BigInteger, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    group = relationship("Group", back_populates="moderation_logs")


class FilterRule(Base):
    """Keyword auto-response filters."""
    __tablename__ = "filter_rules"

    id = Column(Integer, primary_key=True, autoincrement=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)
    keyword = Column(String(128), nullable=False)
    reply_text = Column(Text, nullable=False)
    is_enabled = Column(Boolean, default=True)
    match_type = Column(String(32), default="contains")  # exact, contains

    group = relationship("Group", back_populates="filter_rules")


class PromotionTemplate(Base):
    """Saved promotional message template with custom inline buttons."""
    __tablename__ = "promotion_templates"

    id = Column(Integer, primary_key=True, autoincrement=True)
    title = Column(String(128), nullable=False)
    text = Column(Text, nullable=False)
    media_url = Column(String(512), nullable=True)
    buttons_json = Column(Text, default="[]")  # JSON list of [{"text": "...", "url": "..."}]
    created_by_user_id = Column(BigInteger, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)


class ScheduledMessage(Base):
    """Scheduled message for broadcast."""
    __tablename__ = "scheduled_messages"

    id = Column(Integer, primary_key=True, autoincrement=True)
    group_id = Column(Integer, ForeignKey("groups.id", ondelete="CASCADE"), nullable=False)
    text = Column(Text, nullable=False)
    interval_minutes = Column(Integer, default=1440)  # Once a day default
    next_run_at = Column(DateTime, nullable=False)
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime, default=datetime.utcnow)
